def material_icon_key(name: str) -> str:
    if not name:
        return "default"
    name_words = _tokenize_query(name)
    if not name_words:
        return "default"
    best_key = "default"
    best_score = 0
    for key, rule_words in _ICON_RULE_WORDS:
        score = sum(1 for nw in name_words for rw in rule_words if _words_match(nw, rw))
        if score > best_score:
            best_score = score
            best_key = key
    return best_key


