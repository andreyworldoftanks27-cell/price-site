# ---------- "Живі ціни" із зовнішніх джерел (для товарів, яких нема у нас) ----------
#
# Коли людина шукає в каталозі щось, чого у нашій базі взагалі немає — раніше
# єдиний варіант був просто нічого не знайти. Тепер для НЕБАГАТЬОХ (навмисно!)
# добре перевірених зовнішніх джерел намагаємося показати реальні ціни прямо
# на сторінці, а не просто дати посилання кудись.
#
# ВАЖЛИВО, чому це реалізовано саме так, а не "як зі скрейпінгом зазвичай":
#   - Prom.ua: robots.txt забороняє автоматичний доступ взагалі — не чіпаємо.
#   - E-Katalog (ek.ua): robots.txt забороняє саме сторінки пошуку й товару —
#     не чіпаємо, лишаємо тільки як посилання (людина своїм браузером може,
#     боту — не можна, це різні речі).
#   - Hotline.ua: пошук robots.txt не забороняє, але сторінка — JS-додаток
#     (SPA), без браузера з виконанням JS звичайним запитом із сервера
#     отримуємо порожню "заглушку" замість даних — втягувати сюди повноцінний
#     headless-браузер (Playwright+Chromium) заради цього на невеликому
#     Railway-сервісі — завелика і крихка ціна, не робимо цього зараз.
#   - Епіцентр К: сторінки КАТЕГОРІЙ (не пошуку!) — звичайний серверний HTML
#     з реальними цінами в тексті, і robots.txt забороняє лише /search/, не
#     сторінки категорій. Тому йдемо в обхід їхнього пошуку: тримаємо свій
#     маленький список "запит → конкретна сторінка категорії Епіцентру",
#     і якщо запит користувача співпадає з одним із них — підвантажуємо
#     САМЕ ЦЮ сторінку (дозволено) і дістаємо з неї кілька реальних цін.
#   - Rozetka (окремий піддомен build.rozetka.com.ua, саме для будматеріалів):
#     той самий підхід — сторінки категорій, а не пошуку (їхній власний
#     /search/ теж недоступний для перевірки й не використовується), звичайний
#     серверний HTML (без потреби в JS, перевірено), robots.txt без
#     бланкетної заборони на ці конкретні категорії. Структура посилань на
#     товар у них ІНША за Епіцентр (".../p<ID>/" замість ".../shop/....html"),
#     тому fetch_live_prices нижче приймає патерн посилання як параметр, а не
#     жорстко закодований — щоб одна й та сама функція обслуговувала обидва
#     сайти без копіювання коду.
#
# Текстовий розбір HTML — це найкрихкіша частина: я не маю змоги з цього
# середовища відкрити ці сторінки як звичайний браузер і подивитися точні
# class-атрибути картки товару, тому розбір зроблено не по CSS-класах (вони
# можуть бути вгадані неправильно), а по видимому ТЕКСТУ сторінки — шукаємо
# рядки з ціною ("123.45 ₴") і беремо найближчий попередній рядок, схожий на
# назву товару. Це грубіше, ніж розбір по точних класах, але не ламається,
# якщо я вгадав клас неправильно — просто поверне порожній список, сторінка
# каталогу від цього ніяк не постраждає.
#
# Патерн посилання на сторінку товару — для кожного сайту свій (структура
# URL різна), тому визначаємо обидва ТУТ, ще до списку EXTERNAL_LIVE_SOURCES
# нижче (там вони одразу й використовуються).
_EPICENTR_PRODUCT_HREF_RE = re.compile(r"/shop/[^\"'\s]+\.html")
# Товар Rozetka: ".../ua/<слаг-або-id>/p<ID>/" (перевірено на реальних
# сторінках категорій build.rozetka.com.ua) — ловимо будь-яке посилання, що
# містить "/pNNNN" з необов'язковим завершальним слешем.
_ROZETKA_PRODUCT_HREF_RE = re.compile(r"/p\d+(?:[/?#]|$)")
# Товар Vencon.ua: "/products/<слаг>" (перевірено на реальній сторінці
# категорії /catalog/truby) — на відміну від Епіцентру й Rozetka, тут немає
# числового ID у посиланні, лише текстовий слаг, тому патерн — за самим
# префіксом шляху.
_VENCON_PRODUCT_HREF_RE = re.compile(r"/products/[^\"'\s]+")

# Vista.ua: товар — ".../<слаг-категорії>/p<ID>" (перевірено живим запитом
# до реальної сторінки категорії поліпропіленових труб) — ТОЧНО та сама
# форма посилання, що й у Rozetka ("/pNNNN" у кінці шляху), хоча самі сайти
# між собою не пов'язані — тому просто повторно використовуємо
# _ROZETKA_PRODUCT_HREF_RE нижче, а не заводимо дублікат регулярки.
#
# Budia.ua і Будмаг (strojmag.ua): товар лежить ПРЯМО під коренем домену
# (budia.ua/<слаг>) або під мовним префіксом (strojmag.ua/uk/<слаг>) — на
# відміну від Епіцентру/Rozetka/Vencon тут НЕМАЄ спільного префікса шляху
# типу "/shop/" чи "/products/", за яким можна було б однозначно відділити
# товар від сторінки категорії/меню одним лише шляхом. Але на реальних
# перевірених сторінках обох сайтів слаг товару (на відміну від слага
# категорії чи статичної сторінки типу "kontakt"/"o-kompanii") завжди
# містить ЦИФРУ (розмір/марка/вага — "25kg", "500", "10h10") — тому ловимо
# саме це. Якщо регулярка випадково зачепить ще й якийсь службовий чи
# категорійний рядок — це нешкідливо: нижче в fetch_live_prices посилання
# без ціни поруч просто пропускається (continue), а не потрапляє в
# результат.
_BUDIA_PRODUCT_HREF_RE = re.compile(r"budia\.ua/[a-z][a-z0-9-]*\d[a-z0-9-]*")
_STROJMAG_PRODUCT_HREF_RE = re.compile(r"strojmag\.ua/uk/(?!katalog/)[a-z][a-z0-9-]*\d[a-z0-9-]*")


