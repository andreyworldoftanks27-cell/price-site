# Кирилично-латинські "двійники" — літери, що виглядають ОДНАКОВО в обох
# алфавітах, але для комп'ютера це геть різні символи Unicode. Саме це
# виявилось справжньою причиною скарги "cm 117 не знаходить": товар у базі
# записаний як "Церезіт СМ 117" — кириличні С і М (Es, Em), зовні невідмінні
# від латинських C і M, просто тому що прайс-лист колись набирали/копіювали
# в Excel без єдиного стандарту розкладки. Це НЕ та сама проблема, що й
# "cement 117" (там немає жодного збігу літер узагалі, лише значення слова,
# і це свідомий компроміс, пояснений раніше) — тут літери буквально ті самі
# НА ВИГЛЯД, просто різний алфавіт, тому рішення інше: привести ОБИДВА боки
# порівняння (і цей блок, і сам запит у catalog.html, див. tokenizeQuery)
# до єдиної "канонічної" (латинської) форми для КОНКРЕТНО цих літер.
#
# Навмисно лише кілька однозначних двійників, а не весь кириличний алфавіт
# — "к" і "н", наприклад, теж іноді плутають із "k"/"h", але це одні з
# найчастотніших літер у звичайних кириличних словах, і фолдити їх
# ризикованіше (більше шансів на випадковий збіг зі словом, що не має
# жодного стосунку до запиту) за наявну користь.
_HOMOGLYPH_FOLD_MAP = str.maketrans({
    "а": "a", "с": "c", "е": "e", "м": "m",
    "о": "o", "р": "p", "т": "t", "х": "x", "у": "y",
})


def _fold_homoglyphs(text: str) -> str:
    return text.translate(_HOMOGLYPH_FOLD_MAP)


# Окремий, РОЗСЛАБЛЕНИЙ токенізатор — САМЕ для find_live_sources нижче
# (порівняння запиту користувача з ключовими словами EXTERNAL_LIVE_SOURCES).
# _tokenize_query вище відкидає короткі (< 3 символів) токени — це правильно
# для блоку локального пошуку (build_search_blob), але ламало зовнішній
# пошук за кодами товарних ліній на кшталт "CM 117" (Ceresit): "cm" — лише
# 2 символи, тому ВІДКИДАВСЯ ще до порівняння, і запит "cm 117" ніколи не
# міг знайти жодного джерела, хоч би яке ключове слово я туди додав.
# Користувач прямо попросив: "має шукати навіть так, щоб можна було знайти
# прям будь-який запит... головне щоб шукало". Тому тут: (1) короткі
# токени НЕ відкидаються (лише службові слова-стоп), і (2) фолдинг
# кирилично-латинських двійників ДО токенізації — щоб "ceresit" (латиницею)
# і "церезит"/"церезіт" (кирилицею) порівнювались в однаковій формі, не
# лишень в сторону локального пошуку, як було раніше.
_LIVE_MATCH_WORD_RE = re.compile(r"[a-zа-яіїєґ0-9]+")


def _tokenize_for_live_match(text: str) -> list[str]:
    folded = _fold_homoglyphs(text.lower())
    return [w for w in _LIVE_MATCH_WORD_RE.findall(folded) if w not in _SEARCH_STOPWORDS]


def build_search_blob(name: str, category: str, supplier: str) -> str:
    """Готовий рядок для data-search у catalog.html — див. пояснення вище."""
    base_text = " ".join([
        name or "",
        translate_material_name(name or "", "ru"),
        category or "",
        translate_category(category or "", "ru"),
        supplier or "",
    ])

    extra: set[str] = set()
    for w in _tokenize_query(base_text):
        extra.update(_EN_REVERSE_WORDS.get(w, ()))
    for bm in _BRAND_RE.finditer(base_text):
        extra.update(BRAND_ALIASES.get(bm.group(0).lower(), ()))

    if extra:
        base_text = base_text + " " + " ".join(sorted(extra))
    # Фолдинг — ОСТАННІМ кроком, після lower(): і сам текст, і EN/бренд-
    # синоніми вище вже мають бути в блоці, перш ніж до них застосується
    # заміна літер (деякі синоніми — чиста латиниця, фолдинг на них просто
    # не вплине, оскільки мапа заміняє лише кириличні літери).
    return _fold_homoglyphs(base_text.lower())


templates.env.filters["searchblob"] = build_search_blob

# Частые сокращения поставщиков в названиях товарів — "д/підлоги" вместо
# "для підлоги", "2компл." вместо "двокомпонентний" и т.п. Разворачиваем их
# для строки "Повна назва" на странице товара, чтобы название можно было
# прочитать полностью, без сокращений. Порядок важен: более длинные и
# специфичные сокращения проверяем раньше более коротких, чтобы они не
# "срабатывали" по кусочку общего шаблона (например "звукоіз.еф." — раньше
# отдельных "еф." и "компл.").
_ABBREVIATIONS = [
    (r"звукоіз\.\s*еф\.", "звукоізоляційним ефектом"),
    (r"\b2\s*компл?\.", "двокомпонентний"),
    (r"\b1\s*компл?\.", "однокомпонентний"),
    (r"\bд/", "для "),
    (r"\bб/", "без "),
    (r"\bз/", "із "),
    (r"\bеф\.", "ефект"),
    (r"\bкомпл?\.", "компонентний"),
    (r"\bморозост\.", "морозостійкий"),
    (r"\bводост\.", "водостійкий"),
    (r"\bуніверс\.", "універсальний"),
]
_ABBREV_RE = [(re.compile(pat, re.IGNORECASE), repl) for pat, repl in _ABBREVIATIONS]


def expand_material_name(name: str) -> str:
    """Разворачивает частые сокращения в названии товара в полные слова —
    см. _ABBREVIATIONS выше. Используется для строки "Повна назва" на
    странице истории товара."""
    if not name:
        return name
    result = name
    for pattern, repl in _ABBREV_RE:
        result = pattern.sub(repl, result)
    return re.sub(r"\s{2,}", " ", result).strip()


