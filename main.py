def _find_card_root(anchor, href_re, max_levels: int = 8):
    """
    Товар на сторінці категорії — це посилання <a href=".../xxx.html">
    (назва або картинка товару) всередині якоїсь "картки" (div/li/тощо),
    де поряд лежить і ціна. Ми НЕ знаємо точних CSS-класів цієї картки
    (немає змоги відкрити сайт як браузер із цього середовища, щоб
    подивитися розмітку), тому знаходимо межу картки іншим способом:
    піднімаємось від самого посилання вгору по батьках, поки в межах
    поточного батька лежить РІВНО ОДНЕ посилання на товар. Щойно їх стає
    більше одного — значить, піднялися вище за межу картки (потрапили в
    контейнер із кількома товарами), і треба зупинитись на попередньому
    рівні. Так ми отримуємо саме "картку" цього конкретного товару, а не
    всю сітку одразу — і беремо ціну, що реально лежить поруч із ним, а
    не першу-ліпшу ціну на сторінці.
    """
    # Рахуємо РІЗНІ href, а не кількість тегів <a> — у картки товару часто
    # є ДВА посилання на один і той самий товар (картинка окремим <a> і
    # назва окремим <a>, з однаковим href). Якщо рахувати голі теги, межа
    # картки "виявлялася" вже на першому ж рівні (бо там одразу 2 теги), і
    # ми не встигали піднятися навіть до самої картки з ціною всередині —
    # саме так загубився перший товар у власному тестовому прогоні.
    best = anchor
    node = anchor
    for _ in range(max_levels):
        parent = getattr(node, "parent", None)
        if parent is None or not hasattr(parent, "find_all"):
            break
        links_here = parent.find_all("a", href=href_re)
        distinct_hrefs = {a.get("href") for a in links_here}
        if len(distinct_hrefs) <= 1:
            best = parent
            node = parent
            continue
        break
    return best


async def fetch_live_prices(url: str, href_re=None, scan_limit: int = 100) -> list[dict]:
    """
    Тягне реальні товари (назва + ціна + ПОСИЛАННЯ на саму сторінку товару)
    зі сторінки КАТЕГОРІЇ (не пошуку — дивись пояснення вище) будь-якого з
    джерел у EXTERNAL_LIVE_SOURCES. Повертає [] при БУДЬ-ЯКІЙ проблемі
    (мережа, таймаут, несподівана розмітка) — виклик цієї функції НІКОЛИ не
    повинен зламати сторінку каталогу чи навіть просто сповільнити її надовго.

    href_re — патерн посилання на сторінку ТОВАРУ, свій для кожного сайту
    (структура URL різна: Епіцентр — ".../shop/....html", Rozetka —
    ".../pNNNN/"), тому ЦЯ функція більше не прив'язана до одного сайту:
    заклик без href_re лишається сумісним зі старими викликами (підставляє
    патерн Епіцентру за замовчуванням).

    scan_limit — скільки карток товару взагалі РОЗІБРАТИ зі сторінки.

    РАНІШЕ ця функція сама обрізала результат до top-N НАЙДОРОЖЧИХ (і саме
    ЦЕЙ обрізаний список кешувався на годину за URL) — тому для "труба 25" і
    "труба 35" (той самий URL категорії "труби" на Vencon.ua) показувався
    РІВНО ОДНАКОВИЙ список, без жодного зв'язку з типорозміром із самого
    запиту: користувач про це прямо написав. Тепер функція повертає ПОВНИЙ
    розібраний набір (до scan_limit, усе ще відсортований за ціною, найдорожчі
    спочатку — як і раніше) і кешує САМЕ його; вибір і сортування під
    конкретний запит (чи товар реально згадує "25"/"35" в назві) робить
    _rank_live_items() нижче, ПІСЛЯ кешу — тобто сам мережевий запит і розбір
    сторінки лишаються такими ж рідкісними (кеш за URL працює, як і раніше),
    а релевантність рахується щоразу наново, дешево, вже на готових даних.

    scan_limit БУВ 20 — і це й лишалось справжньою причиною того, що "труба
    25" і "труба 28" усе одно показували ОДНАКОВИЙ список, навіть після
    виправлення вище: перевірено живим запитом (справжній HTML категорії,
    без виконання JS — те саме, що бачить і ця функція) — на сторінці
    "труби" Vencon.ua реально 73 різні товари, а в Rozetka ("Трубний
    металопрокат") — 61+ на першій же сторінці (і є ще сторінка 2). Типорозмір
    "25" чи "28", якого шукає людина, майже завжди лежить ДЕСЬ ЗА межею
    перших 20 карток у порядку, в якому вони йдуть у HTML (а він не
    впорядкований за розміром) — тобто жодна з двох карток із потрібним
    числом у назві просто ніколи не потрапляла в кеш, і _rank_live_items()
    нижче рахувала 0 збігів для ОБОХ запитів і для ОБОХ однаково відкочувалась
    до сортування за ціною — звідси й "список не змінюється зовсім". Підняття
    до 100 покриває Vencon.ua повністю і більшу частину першої сторінки
    Rozetka (повної підтримки сторінок 2+ все ще нема — це вже окрема, більша
    зміна, не потрібна для переважної більшості запитів).

    Товар без знайденого посилання НЕ включаємо в результат узагалі —
    людині потрібно саме клікабельне посилання на конкретний товар, а не
    просто рядок тексту (раніше ця функція розбирала голий текст сторінки
    без прив'язки до HTML-посилань і тому не знала справжньої адреси
    товару — це і було виправлено тут).
    """
    href_re = href_re or _EPICENTR_PRODUCT_HREF_RE

    cached = _EXTERNAL_PRICE_CACHE.get(url)
    if cached and (time.time() - cached[0]) < _EXTERNAL_PRICE_CACHE_TTL:
        return cached[1]

    # Заголовки, схожі на звичайний браузер — лише User-Agent (як було
    # раніше) для деяких сайтів є ознакою бота сам по собі: немає
    # Accept/Accept-Language/Referer, які завжди шле справжній браузер.
    # Referer — головна сторінка ТОГО Ж САМОГО сайту (а не завжди
    # epicentrk.ua, як було раніше, коли функція обслуговувала лише один
    # сайт) — беремо з домену запитуваного url.
    parsed_url = urlparse(url)
    request_headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
            "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
        ),
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "uk-UA,uk;q=0.9,ru;q=0.8,en;q=0.7",
        "Referer": f"{parsed_url.scheme}://{parsed_url.netloc}/",
    }

    html = None
    last_error = None
    # РАНІШЕ тут було дві послідовні спроби (6с, потім 15с), якщо перша не
    # встигала. Користувач поскаржився, що пошук займає 8-10 секунд — і це
    # саме причина: сайт, що стабільно відповідає, скажімо, за 7-8с (повільний,
    # але не заблокований), ВИТРАЧАВ 6с на невдалу першу спробу, а потім ще
    # кілька секунд на другу — разом саме ті 8-10+с. Одна спроба з розумним
    # тайм-аутом (8с) прибирає цю "подвійну сплату" і для caller'а (/live-search,
    # уже й так опитує кілька джерел ПАРАЛЕЛЬНО через asyncio.gather) означає
    # передбачуваний максимум ~8с на запит замість непередбачуваних ~21с.
    try:
        async with httpx.AsyncClient(
            timeout=8.0,
            headers=request_headers,
            follow_redirects=True,
        ) as client:
            resp = await client.get(url)
            resp.raise_for_status()
            html = resp.text
    except Exception as exc:
        last_error = exc

    if html is None:
        logger.warning(
            "live-price fetch failed for %s after retries: %r", url, last_error
        )
        _EXTERNAL_PRICE_CACHE[url] = (time.time(), [])
        _EXTERNAL_PRICE_DIAGNOSTICS[url] = {
            "checked_at": time.time(),
            "items_found": 0,
            "links_found": 0,
            "status": "fetch_error",
            "error": repr(last_error),
            "debug_first_card": None,
            "sample_hrefs": None,
        }
        return []

    results = []
    try:
        soup = BeautifulSoup(html, "html.parser")
        for tag in soup(["script", "style", "noscript"]):
            tag.decompose()

        product_links = soup.find_all("a", href=href_re)
        if not product_links:
            # 200 OK, але жодного посилання на товар не знайдено під наш
            # патерн. Перш ніж здаватися — логуємо кілька РЕАЛЬНИХ href з
            # продакшну (будь-які посилання на сторінці, не лише ті, що
            # підійшли під href_re): це дасть точний формат посилань ЦЬОГО
            # сайту, замість гри в угадайку з цієї пісочниці (де прямий
            # доступ до сайту заблокований мережевою політикою, тому
            # побачити живу розмітку інакше не вийде).
            all_links = soup.find_all("a", href=True)
            sample_hrefs = []
            for a in all_links:
                h = a.get("href") or ""
                if h and h not in sample_hrefs:
                    sample_hrefs.append(h)
                if len(sample_hrefs) >= 8:
                    break
            logger.warning(
                "live-price: 0 product links on %s (body %d bytes, href_re=%s). "
                "Sample of all hrefs found: %d, sample: %r",
                url, len(html), href_re.pattern, len(all_links), sample_hrefs,
            )
        seen_urls = set()
        debug_first_card = None  # для логу, якщо знову 0 результатів
        for link in product_links:
            href = link.get("href") or ""
            if not href:
                continue
            product_url = urljoin(url, href)
            if product_url in seen_urls:
                continue

            card = _find_card_root(link, href_re)
            card_text = card.get_text("\n")
            card_lines = [ln.strip() for ln in card_text.split("\n") if ln.strip()]
            # Число ціни і сам символ "₴" на реальних сайтах дуже часто
            # лежать у СУСІДНІХ, але ОКРЕМИХ тегах (наприклад
            # <span>170</span><span>₴</span>) — get_text("\n") тоді
            # розкладає їх на РІЗНІ "рядки", і пошук по кожному рядку
            # окремо (як було раніше) ніколи їх не з'єднає, хоча сама
            # регулярка (де \s вже матчить і перенос рядка) це б
            # спіймала. Тому ціну шукаємо по ВСЬОМУ тексту картки одним
            # блоком — саме це і було причиною "130 посилань знайдено, 0
            # товарів витягнуто" в продакшн-логах.
            #
            # РОЗДІЛЬНИК між окремими тегами — "\x00" (символ, якого не
            # буває у звичайному тексті сторінки), а НЕ звичайний пробіл,
            # як було раніше. Причина: Будмаг (strojmag.ua) форматує великі
            # ціни ЗВИЧАЙНИМ пробілом як роздільником розрядів прямо
            # ВСЕРЕДИНІ ОДНОГО текстового вузла — "7 675.36 грн." (перевірено
            # живим запитом до реальної сторінки категорії "труби": це й
            # справді один <span>, а не два різних теги). Поки роздільник
            # між тегами був звичайним пробілом, його було неможливо
            # відрізнити від ТАКОГО пробілу всередині ціни — і попередня
            # версія регулярки (яка з цієї ж причини забороняла пробіл у
            # числі) просто відкидала "7 " і бачила тільки "675.36",
            # показуючи ціну в 10+ разів меншою за реальну. "\x00" — це
            # НЕ пробіл (під \s у регулярці не підпадає) — тому тепер
            # звичайний пробіл УСЕРЕДИНІ ціни (Будмаг) і "пробіл", яким
            # get_text раніше штучно склеював РІЗНІ теги (через що й
            # обмежили пробіл першого разу — "27" з одного тега плюс
            # "279.00" з іншого зливались у безглузде "27279.00"),
            # більше не плутаються: справжній пробіл лишається пробілом,
            # а межа між тегами — "\x00", який регулярка нижче ніколи не
            # сприйме за частину числа.
            card_flat = card.get_text("\x00")
            # Прибираємо бейджі знижки ("-245.26 ₴", "-27%") ДО пошуку
            # ціни — інакше сума знижки (яка виглядає як звичайна ціна)
            # може переплутатися зі справжньою ціною товару.
            card_flat_for_price = _DISCOUNT_BADGE_RE.sub(" ", card_flat)

            # У картці нерідко лишається ОДРАЗУ дві суми з "₴": стара
            # закреслена ціна і справжня (знижена) — і в тексті стара
            # найчастіше йде ПЕРШОЮ. Тому замість "перший знайдений збіг"
            # беремо НАЙМЕНШУ з усіх дійсних сум картки: знижена ціна за
            # означенням менша за стару, а якщо знижки нема — кандидат
            # просто один і це нічого не змінює.
            price = None
            for int_part, dec_part in _PRICE_RE.findall(card_flat_for_price):
                price_str = int_part.replace(" ", "").replace("\xa0", "")
                if dec_part:
                    price_str = f"{price_str}.{dec_part}"
                try:
                    candidate_price = float(price_str)
                except ValueError:
                    continue
                if candidate_price <= 0:
                    continue
                if price is None or candidate_price < price:
                    price = candidate_price

            if debug_first_card is None:
                debug_first_card = {
                    "href": href,
                    "link_text": link.get_text(" ", strip=True)[:80],
                    "price_found": price,
                    # "\x00" (межа між тегами, див. коментар вище) замінено
                    # на читабельне " | " лише ДЛЯ ЦЬОГО діагностичного
                    # зразка — сам пошук ціни вище працює з "\x00" напряму.
                    "card_flat_sample": card_flat[:400].replace("\x00", " | "),
                }

            if price is None:
                continue

            # Назва — текст самого посилання (зазвичай і є назвою товару
            # або містить її в title/alt картинки); якщо посилання не
            # містить тексту (наприклад, це посилання-картинка) — беремо
            # title/alt, а як останній варіант — перший "схожий на назву"
            # рядок картки.
            name = link.get_text(" ", strip=True)
            if not name:
                name = (link.get("title") or "").strip()
            if not name:
                img = link.find("img")
                if img:
                    name = (img.get("alt") or img.get("title") or "").strip()
            if not name:
                for ln in card_lines:
                    if _PRICE_RE.search(ln) or _RATING_LINE_RE.match(ln):
                        continue
                    if ln.lower() in _EPICENTR_NOISE_LINES:
                        continue
                    if len(ln) < 8 or len(ln) > 160:
                        continue
                    if not re.search(r"[a-zA-Zа-яА-ЯіІїЇєЄґҐ]", ln):
                        continue
                    name = ln
                    break
            if not name or len(name) < 4:
                continue

            seen_urls.add(product_url)
            results.append({"name": name, "price": price, "url": product_url})
            if len(results) >= scan_limit:
                break

        # Найдорожчі спочатку (користувач попросив явно) — і ЛИШЕ ТЕПЕР,
        # після того як розібрали до scan_limit карток, а не перших-ліпших.
        # Обрізання до конкретної кількості для показу — вже ПІСЛЯ кешу, у
        # _rank_live_items() нижче (див. пояснення в докстрінгу вище).
        results.sort(key=lambda r: r["price"], reverse=True)

        if product_links and not results:
            # Посилання на товари є, а жодна картка не дала ні ціни, ні
            # назви — найімовірніше, розмітку сторінки знову змінили і
            # наші регулярки (_PRICE_RE / card-root) більше не
            # потрапляють у потрібні теги. Це вже сигнал щодо ПАРСИНГУ,
            # а не мережі/блокування (бо посилання самі знайшлися).
            # Додатково лишаємо сирий приклад першої картки — щоб одразу
            # побачити, чого саме бракує (ціни чи назви), не ганяючи
            # деплой по колу ще раз.
            logger.warning(
                "live-price: found %d product links on %s but extracted 0 items "
                "(price/name parsing likely out of date). First card debug: %r",
                len(product_links), url, debug_first_card,
            )

        _EXTERNAL_PRICE_DIAGNOSTICS[url] = {
            "checked_at": time.time(),
            "items_found": len(results),
            "links_found": len(product_links),
            "status": (
                "ok" if results
                else "no_links" if not product_links
                else "parse_zero"
            ),
            "error": None,
            "debug_first_card": debug_first_card if not results and product_links else None,
            "sample_hrefs": sample_hrefs if not product_links else None,
        }
    except Exception as exc:
        logger.exception("live-price: unexpected parsing error for %s", url)
        results = []
        _EXTERNAL_PRICE_DIAGNOSTICS[url] = {
            "checked_at": time.time(),
            "items_found": 0,
            "links_found": 0,
            "status": "parse_error",
            "error": repr(exc),
            "debug_first_card": None,
            "sample_hrefs": None,
        }

    _EXTERNAL_PRICE_CACHE[url] = (time.time(), results)
    return results


_PAREN_RE = re.compile(r"\([^)]*\)")


def _rank_live_items(items: list[dict], query_tokens: list[str], limit: int = 8) -> list[dict]:
    """
    items — ПОВНИЙ розібраний набір від fetch_live_prices (до scan_limit,
    відсортований за ціною, найдорожчі спочатку). Користувач прямо
    поскаржився: "труба 25" і "труба 35" показували ОДНАКОВІ зовнішні
    результати — бо раніше просто бралися top-N найдорожчих з усієї
    категорії, без жодного урахування типорозміру з самого запиту.

    Тепер товари, чия НАЗВА (а не вся картка — назви на зовнішніх сайтах
    зазвичай містять і бренд, і типорозмір) реально містить токен запиту
    (особливо числа — діаметр/типорозмір, саме це й було відсутнє), підняти
    нагору; товари без жодного збігу лишаються внизу, а не зникають
    узагалі — якщо збігів немає ЖОДНИХ, людина все одно побачить чесний
    топ "найдорожчих" цієї категорії (є що показати — краще показати, ніж
    порожньо), просто без оманливого вигляду "це саме те, що ти шукав".

    Сортування Python стабільне — тому серед товарів з ОДНАКОВОЮ кількістю
    збігів (у т.ч. серед 0-у-всіх, якщо нічого не збіглося) зберігається
    початковий порядок за ціною — КРІМ одного додаткового рівня, описаного
    нижче (complexity bucket).

    Користувач поскаржився на прикладі "цемент": для такого однослівного
    запиту майже ВСІ товари категорії містять "цемент" прямо в назві (це ж
    цемент) — тобто match_count однаковий практично для всіх, і перемагає
    голе сортування за ціною, яке піднімає нагору не "звичайний" цемент, а
    найдорожчі СПЕЦІАЛЬНІ варіанти (гідроізоляційний, швидкотверднучий,
    для холодної пори року...) — формально теж "цемент", просто не те,
    що людина, скоріш за все, мала на увазі простим словом "цемент".
    Перевірено на реальних назвах категорії цементу Епіцентру: прості
    товари ("Цемент М 400 5кг", "Цемент ПЦ І 500 Н 5 кг") — КОРОТШІ за
    назвою, ніж спеціалізовані варіанти з купою додаткових слів
    ("Цемент гидроизоляционный ГИР-2 М-600 ВС Плюс сульфатостойкий 50 кг").
    Тому ДРУГИЙ ключ сортування (ПІСЛЯ match_count, ПЕРЕД ціною) — "бакет
    складності" назви (довжина без дужок, округлена вниз до 20 символів):
    товари з КОРОТШОЮ, простішою назвою — тобто ймовірніше саме "звичайний"
    варіант — підіймаються вище товарів з довшою, навантаженою додатковими
    словами назвою, навіть якщо ті дорожчі. Це навмисно ГРУБИЙ розподіл по
    бакетах по 20 символів (а не точна довжина) — щоб дрібна різниця в
    пару символів між двома однаково "звичайними" товарами не перебивала
    сортування за ціною всередині одного бакета, це лишається попереднім
    принципом "показувати найвищу можливу ціну" серед порівнянних товарів.

    ВАЖЛИВО: бакет складності рахується ЛИШЕ для товарів, що вже мають
    match_count > 0 (хоч щось зі слів запиту реально є в назві). Для
    товарів з match_count == 0 бакет ЗАВЖДИ 0 — інакше для сайтів типу
    Vencon.ua, де назви товарів — це просто бренд+технічний код без жодних
    загальних слів ("Conex Banninger Press Inox Ø42x1,5 мм", жодного
    "труба"/"муфта" в тексті), ПРИ ЗАПИТІ "труба муфта з'єднувальна"
    match_count був би 0 для геть УСІХ товарів категорії — і без цього
    застереження бакет складності став би ГОЛОВНИМ критерієм замість
    допоміжного, піднімаючи нагору випадкові товари з найкоротшою назвою
    (напр. "Albertoni 238/5") лише тому, що вона коротка, а не тому, що
    вона хоч якось стосується запиту. Користувач саме на цьому прикладі
    і впіймав цю помилку. З цим застереженням для товарів без жодного
    збігу бакет завжди однаковий (0) — і для них, як і раніше до
    запровадження бакета, вирішує тільки ціна.
    """
    if not query_tokens:
        return items[:limit]

    def sort_key(it: dict) -> tuple[int, int]:
        # Артикул/код товару майже завжди в дужках у кінці назви (напр.
        # "(R3560044032)") — і, на реальних даних, ЦИФРИ коду регулярно
        # випадково містять шуканий типорозмір як підрядок ("35" усередині
        # "R3560044032"), підіймаючи зовсім не той товар. Прибираємо вміст
        # дужок ПЕРЕД порівнянням — типорозмір завжди в основній частині
        # назви, а не в самому коді; та ж паренс-очищена назва йде і в
        # розрахунок "бакета складності" нижче.
        name_l = _PAREN_RE.sub(" ", it["name"]).lower()
        match_count = sum(1 for tok in query_tokens if tok in name_l)
        complexity_bucket = (len(name_l) // 20) if match_count > 0 else 0
        return (match_count, -complexity_bucket)

    ranked = sorted(items, key=sort_key, reverse=True)
    return ranked[:limit]


def _relevant_prefix_count(ranked_items: list[dict], query_tokens: list[str]) -> int:
    """
    ranked_items — уже відсортований _rank_live_items() результат (спочатку
    товари з найбільшим match_count). Повертає, СКІЛЬКИ товарів від початку
    списку мають match_count > 0 (реально згадують хоч щось із запиту в
    назві) — ранкінг стабільно спадний за match_count, тому досить дійти до
    ПЕРШОГО товару з нульовим збігом і зупинитись: усі товари після нього
    теж 0 (інакше вони стояли б раніше).

    Навіщо: /live-search нижче віддає це число як "relevant_count" разом
    зі списком — catalog.html використовує його, щоб показати "товари, що
    справді відповідають запиту" окремо від "загальної категорії" нижче
    (користувач прямо попросив: "1 точний відповідь, пару подібних
    варіантів, і може десь внизу 'компоненти, які можуть знадобитися'") —
    замість одного суцільного списку, де, якщо жоден товар каталогу не
    містить слів запиту буквально (поширена ситуація на сайтах з
    "технічними" назвами товарів на кшталт Vencon.ua), людина бачить
    товари, що виглядають як випадковий набір, без жодного пояснення,
    чому саме вони нагорі.
    """
    if not query_tokens:
        return 0
    count = 0
    for it in ranked_items:
        name_l = _PAREN_RE.sub(" ", it["name"]).lower()
        if any(tok in name_l for tok in query_tokens):
            count += 1
        else:
            break
    return count


# Прийменники/сполучники — не несуть сенсу для пошуку категорії, тому не
# враховуються як "слова" при розбитті запиту/ключових фраз на токени.
_SEARCH_STOPWORDS = {
    "для", "в", "на", "і", "й", "та", "по", "з", "із", "до", "під", "над",
    "о", "об", "у", "без", "про", "як", "что", "как", "это", "или", "або",
}
_WORD_RE = re.compile(r"[a-zа-яіїєґ0-9]+")


def _tokenize_query(text: str) -> list[str]:
    words = _WORD_RE.findall(text.lower())
    return [w for w in words if len(w) >= 3 and w not in _SEARCH_STOPWORDS]


# Окремий, "сирий" токенізатор для _rank_live_items нижче — _tokenize_query
# вище навмисне відкидає короткі токени (len < 3) і службові слова, бо
# призначений для зіставлення із КУРОВАНИМИ ключовими фразами джерел
# (find_live_sources). Для ранжування зовнішніх результатів за ТИПОРОЗМІРОМ
# це якраз шкідливо — "25", "32", "Ø20" часто рівно 2 символи і є НАЙВАЖЛИВІШОЮ
# частиною запиту ("труба 25"), тому тут усі токени (слова й числа, окремо —
# як і в клієнтському tokenizeQuery() у catalog.html) лишаються без фільтра.
_RAW_QUERY_TOKEN_RE = re.compile(r"[a-zа-яіїєґ]+|\d+")


def _split_query_tokens(text: str) -> list[str]:
    return _RAW_QUERY_TOKEN_RE.findall(text.lower())


def _words_match(a: str, b: str) -> bool:
    """
    Порівняння двох слів із допуском на відмінки/форми слова: точний збіг,
    або одне є префіксом іншого (ловить більшість відмінкових закінчень —
    "цемент"/"цементу", "саморіз"/"саморізи" — хоча не всі, бо в укр./рос.
    мовах закінчення іноді змінює й кінець кореня, а не лише додає літери;
    для короткого кореня (<=3 літер, напр. "осб", "пва") вимагаємо точного
    збігу, щоб не ловити випадкові збіги).
    """
    if a == b:
        return True
    shorter, longer = (a, b) if len(a) <= len(b) else (b, a)
    if len(shorter) <= 3:
        return False
    return longer.startswith(shorter)


def _words_fuzzy_match(a: str, b: str) -> bool:
    """
    Другий, ЩИРІШИЙ рівень збігу — підрядок в БУДЬ-ЯКИЙ бік (не лише
    префікс), і використовується ЛИШЕ як fallback, коли _words_match не
    знайшов рівно ЖОДНОГО джерела для всього запиту (див. find_live_sources
    нижче). Ловить більше відмінкових форм і дрібних розбіжностей
    ("трубу" проти "труби", де спільний лише корінь не з початку/кінця),
    ціною трохи більшої кількості випадкових збігів — прийнятний компроміс,
    бо спрацьовує лише тоді, коли точний пошук інакше показав би геть
    нічого.
    """
    if len(a) < 4 or len(b) < 4:
        return a == b
    return a in b or b in a


def find_live_sources(query: str, max_results: int = 6) -> list[dict]:
    """
    Було: find_live_source (однина) повертав ЛИШЕ ОДНЕ, найкраще за
    рахунком, джерело — тому якщо запит однаково добре підходив під
    кілька сайтів одразу (наприклад "цемент" — є і в Епіцентрі, і в
    Rozetka, див. EXTERNAL_LIVE_SOURCES), користувач бачив ціну лише з
    ОДНОГО з них. Користувач прямо попросив показувати варіанти "як в
    Епіцентрі, так і в усіх інших можливих сайтах" одразу — тому тепер
    повертаємо до max_results джерел із НАЙВИЩИМ рахунком (score > 0),
    а не єдине найкраще, і /live-search нижче запитує ціни з КОЖНОГО з
    них паралельно.

    Порівняння — ПО ОКРЕМИХ СЛОВАХ (а не цілою фразою підрядком): рахуємо,
    скільки слів запиту знайшли відповідник серед слів ключових фраз
    категорії. Було: порівняння цілою фразою — тому двослівний запит типу
    "клей пва" не знаходив НІЧОГО, бо жодна curated-фраза не збігалася і
    не містила його цілком.
    """
    # _tokenize_for_live_match (не _tokenize_query!) — навмисно: не
    # відкидає короткі токени ("cm", "ct" — коди товарних ліній) і фолдить
    # кирилично-латинські двійники ДО порівняння (щоб "ceresit" і
    # "церезит"/"церезіт" рахувались однаково) — див. пояснення над
    # визначенням функції. Інакше запит "cm 117" ніколи б не знайшов
    # жодного джерела: "cm" відкидався б ще до порівняння.
    q_words = _tokenize_for_live_match(query)
    if not q_words:
        return []

    # Англійські слова запиту ("cement", "pipe", "glue"...) — РОЗШИРЮЄМО
    # їхніми укр./рос. відповідниками з EN_SEARCH_SYNONYMS (той самий
    # словник, яким build_search_blob розширює ЛОКАЛЬНИЙ пошук нижче за
    # файлом) ДО порівняння з EXTERNAL_LIVE_SOURCES — бо keywords джерел
    # майже всі українською/російською ("цемент", не "cement"), і без
    # цього кроку англійське слово НІКОЛИ б не могло знайти жодного
    # джерела, хоч скільки категорій додай. Користувач прямо показав
    # приклад: "cement" знаходить "cm"/"ceresit" (уже працює), але сам по
    # собі — ні, хоча "цемент" як категорія в нас давно є (Епіцентр,
    # Rozetka, Budia.ua, Будмаг). EN_SEARCH_SYNONYMS визначений НИЖЧЕ за
    # файлом (разом з build_search_blob) — це нормально в Python: виклик
    # (не визначення) функції стається вже після того, як увесь модуль
    # довантажився.
    expanded_words = set(q_words)
    for w in q_words:
        for syn in EN_SEARCH_SYNONYMS.get(w, ()):
            expanded_words.update(_tokenize_for_live_match(syn))
    q_words = list(expanded_words)

    # --- Збір "сирих" збігів: для кожного джерела — МНОЖИНА слів запиту,
    # які воно покриває (а не лише їхню кількість) — множина потрібна
    # нижче, щоб порахувати "рідкісність" кожного слова запиту.
    raw_matches: list[tuple[dict, set]] = []
    for entry in EXTERNAL_LIVE_SOURCES:
        entry_words = entry.get("_kw_words")
        if entry_words is None:
            entry_words = set()
            for kw in entry["keywords"]:
                entry_words.update(_tokenize_for_live_match(kw))
            entry["_kw_words"] = entry_words
        matched = {qw for qw in q_words if any(_words_match(qw, ew) for ew in entry_words)}
        if matched:
            raw_matches.append((entry, matched))

    if not raw_matches:
        # Жодного ТОЧНОГО збігу — перш ніж здатися зовсім, пробуємо
        # ширший fallback-пошук (_words_fuzzy_match, підрядок у будь-який
        # бік). Це НЕ повноцінний повнотекстовий пошук "як у Google" — за
        # такими запитами всюди або явно забороняє robots.txt (власний
        # /search/ Епіцентру, Rozetka, Prom.ua, E-Katalog...), або сторінка
        # результатів — JS-додаток без серверного HTML (Hotline.ua) — тобто
        # його просто нема звідки чесно узяти без порушення чужих правил чи
        # важкого headless-браузера на кожен запит. Це — компроміс:
        # розширює РОЗПІЗНАВАННЯ вже заданих категорій (більше форм слова),
        # а не перелік самих категорій.
        for entry in EXTERNAL_LIVE_SOURCES:
            entry_words = entry["_kw_words"]  # вже закешовано вище
            matched = {qw for qw in q_words if any(_words_fuzzy_match(qw, ew) for ew in entry_words)}
            if matched:
                raw_matches.append((entry, matched))

    # Скільки РІЗНИХ джерел покриває КОЖНЕ слово запиту окремо — рахуємо
    # ТУТ, по готовому raw_matches (а не по сирих токенах ключових фраз):
    # слово "трубы" збігається і з джерелами, де є буквально "трубы", і з
    # "ізоляція труб" (через корінь "труб") — усі вони мають рахуватись як
    # ОДНЕ й те саме, часто вживане слово. Якби рахувати частоту по
    # ЛІТЕРАЛЬНИХ токенах ключових фраз (як було в першій версії цього
    # виправлення), "труб" (лише в "ізоляція труб") і "трубы" (в десятку
    # інших джерел) вважались би РІЗНИМИ, однаково рідкісними словами — і
    # "ізоляція труб" помилково вигравала б у джерела з дійсно рідкісним і
    # специфічним словом "муфта" тим самим чином, яким раніше вигравала
    # просто перша за порядком оголошення категорія.
    word_doc_count: dict[str, int] = {}
    for _entry, matched in raw_matches:
        for qw in matched:
            word_doc_count[qw] = word_doc_count.get(qw, 0) + 1

    # Стабільне сортування: спочатку за рахунком (скільки слів запиту
    # збіглося), а ПРИ РІВНОМУ рахунку — за "рідкісністю" (сума 1/частота
    # по кожному збіглому слову, вище — краще). Користувач поскаржився на
    # прикладі "труба муфта": джерело Rozetka "сантехніка/фітинги" (ЄДИНЕ
    # в усьому списку зі словом "муфта") мало ТОЙ САМИЙ рахунок (1), що й
    # звичайні "труба водопровідна"/"труба каналізаційна" (кожне теж
    # збігається лише з одним словом запиту — "труба"/"трубы", яке є
    # практично в кожному джерелі труб) — і програвало суто через порядок
    # оголошення в списку (diversify-by-shop нижче бере ПЕРШЕ за цим
    # порядком джерело на кожен магазин). Рахунок однаковий, але збіг зі
    # словом "муфта" (1 джерело на весь список) набагато інформативніший
    # за черговий збіг із майже всюдисущим "труба"/"трубы" (8-11 джерел) —
    # рідкісність це і відображає. Порядок рівних і за рахунком, і за
    # рідкісністю лишається таким, як у EXTERNAL_LIVE_SOURCES (sort у
    # Python — стабільний).
    scored = [
        (len(matched), sum(1.0 / word_doc_count[qw] for qw in matched), entry)
        for entry, matched in raw_matches
    ]
    scored.sort(key=lambda t: (t[0], t[1]), reverse=True)

    # РАНІШЕ тут було просто "перші max_results зі scored" — і для запитів
    # типу "клей" це означало ВСІ max_results місць займали категорії
    # ОДНОГО Й ТОГО Ж магазину (Епіцентра — просто бо для клею в нас
    # найбільше його категорій і вони стоять найранішими в списку вище),
    # а інші магазини (Budia.ua, Будмаг, Vista.ua — теж реально
    # перевірені джерела з клеєм, див. вище), маючи ТОЙ САМИЙ рахунок,
    # просто не влазили в ліміт. Користувач прямо поскаржився: "не один
    # магазин, а щоб різні". Тому відбір — у ДВА проходи: спочатку беремо
    # по ОДНОМУ найкращому джерелу з КОЖНОГО магазину (різноманітність
    # важливіша за те, яка саме з однаково релевантних категорій ОДНОГО
    # магазину потрапить у видачу), а решту вільних місць (якщо лишились)
    # заповнюємо наступними за рахунком джерелами — вже без обмеження на
    # магазин, щоб не показувати порожні місця, якщо різних магазинів
    # менше за max_results.
    chosen: list[dict] = []
    seen_shops: set[str] = set()
    for _score, _rarity, entry in scored:
        if len(chosen) >= max_results:
            break
        if entry["shop"] in seen_shops:
            continue
        chosen.append(entry)
        seen_shops.add(entry["shop"])
    if len(chosen) < max_results:
        for _score, _rarity, entry in scored:
            if len(chosen) >= max_results:
                break
            if entry in chosen:
                continue
            chosen.append(entry)
    return chosen


