# правильний основний патерн, не ганяючи деплой по колу.
_EPICENTR_ANY_HTML_HREF_RE = re.compile(r"\.html(?:[?#]|$)")


def _find_card_root(anchor, href_re, max_levels: int = 8):
    """
    Товар на сторінці категорії — це посилання <a href=".../xxx.html">
    (назва або картинка товару) всередині якоїсь "картки" (div/li/тощо),
    де поряд лежить і ціна. Ми НЕ знаємо точних CSS-класів цієї картки
    (немає змоги відкрити сайт як браузер із цього середовища, щоб
    подивитися розмітку), тому знаходимо межу картки іншим способом:
    піднімаємось від самого посилання вгору по батьках, поки в межах
    поточного батька лежить РІВНО ОДНЕ посилання на товар. Щойно їх стає
    більше одного — значить, піднялися вище за межу картки (потрапили в
    контейнер із кількома товарами), і треба зупинитись на попередньому
    рівні. Так ми отримуємо саме "картку" цього конкретного товару, а не
    всю сітку одразу — і беремо ціну, що реально лежить поруч із ним, а
    не першу-ліпшу ціну на сторінці.
    """
    # Рахуємо РІЗНІ href, а не кількість тегів <a> — у картки товару часто
    # є ДВА посилання на один і той самий товар (картинка окремим <a> і
    # назва окремим <a>, з однаковим href). Якщо рахувати голі теги, межа
    # картки "виявлялася" вже на першому ж рівні (бо там одразу 2 теги), і
    # ми не встигали піднятися навіть до самої картки з ціною всередині —
    # саме так загубився перший товар у власному тестовому прогоні.
    best = anchor
    node = anchor
    for _ in range(max_levels):
        parent = getattr(node, "parent", None)
        if parent is None or not hasattr(parent, "find_all"):
            break
        links_here = parent.find_all("a", href=href_re)
        distinct_hrefs = {a.get("href") for a in links_here}
        if len(distinct_hrefs) <= 1:
            best = parent
            node = parent
            continue
        break
    return best


async def fetch_live_prices(url: str, limit: int = 5) -> list[dict]:
    """
    Тягне кілька реальних товарів (назва + ціна + ПОСИЛАННЯ на саму
    сторінку товару) зі сторінки КАТЕГОРІЇ Епіцентру (не пошуку — дивись
    пояснення вище). Повертає [] при БУДЬ-ЯКІЙ проблемі (мережа, таймаут,
    несподівана розмітка) — виклик цієї функції НІКОЛИ не повинен зламати
    сторінку каталогу чи навіть просто сповільнити її надовго.

    Товар без знайденого посилання НЕ включаємо в результат узагалі —
    людині потрібно саме клікабельне посилання на конкретний товар, а не
    просто рядок тексту (раніше ця функція розбирала голий текст сторінки
    без прив'язки до HTML-посилань і тому не знала справжньої адреси
    товару — це і було виправлено тут).
    """
    cached = _EXTERNAL_PRICE_CACHE.get(url)
    if cached and (time.time() - cached[0]) < _EXTERNAL_PRICE_CACHE_TTL:
        return cached[1]

    # Заголовки, схожі на звичайний браузер — лише User-Agent (як було
    # раніше) для деяких сайтів є ознакою бота сам по собі: немає
    # Accept/Accept-Language/Referer, які завжди шле справжній браузер.
    request_headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
            "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
        ),
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "uk-UA,uk;q=0.9,ru;q=0.8,en;q=0.7",
        "Referer": "https://epicentrk.ua/",
    }

    html = None
    last_error = None
    # Дві спроби з різним тайм-аутом: якщо сайт просто повільний (а не
    # заблокував нас) — перша спроба з 6с таймаутом може не встигнути,
    # друга з 15с майже напевно встигне. Якщо обидві падають — це вже
    # скоріш за все не "повільно", а мережева блокування/помилка.
    for attempt, timeout_s in enumerate((6.0, 15.0), start=1):
        try:
            async with httpx.AsyncClient(
                timeout=timeout_s,
                headers=request_headers,
                follow_redirects=True,
            ) as client:
                resp = await client.get(url)
                resp.raise_for_status()
                html = resp.text
            break
        except Exception as exc:
            last_error = exc
            continue

    if html is None:
        logger.warning(
            "live-price fetch failed for %s after retries: %r", url, last_error
        )
        _EXTERNAL_PRICE_CACHE[url] = (time.time(), [])
        return []

    results = []
    try:
        soup = BeautifulSoup(html, "html.parser")
        for tag in soup(["script", "style", "noscript"]):
            tag.decompose()

        product_links = soup.find_all("a", href=_EPICENTR_PRODUCT_HREF_RE)
        if not product_links:
            # 200 OK, але жодного посилання на товар не знайдено під наш
            # патерн. Перш ніж здаватися — пробуємо ширший діагностичний
            # патерн (будь-яке посилання, що закінчується на .html) і
            # логуємо кілька РЕАЛЬНИХ href з продакшну: це дасть точний
            # формат посилань Епіцентру, замість гри в угадайку з цієї
            # пісочниці (де прямий доступ до сайту заблокований мережевою
            # політикою, тому побачити живу розмітку інакше не вийде).
            fallback_links = soup.find_all("a", href=_EPICENTR_ANY_HTML_HREF_RE)
            sample_hrefs = []
            for a in fallback_links:
                h = a.get("href") or ""
                if h and h not in sample_hrefs:
                    sample_hrefs.append(h)
                if len(sample_hrefs) >= 8:
                    break
            logger.warning(
                "live-price: 0 product links on %s (body %d bytes). "
                "Fallback *.html links found: %d, sample: %r",
                url, len(html), len(fallback_links), sample_hrefs,
            )
        seen_urls = set()
        debug_first_card = None  # для логу, якщо знову 0 результатів
        for link in product_links:
            href = link.get("href") or ""
            if not href:
                continue
            product_url = urljoin(url, href)
            if product_url in seen_urls:
                continue

            card = _find_card_root(link, _EPICENTR_PRODUCT_HREF_RE)
            card_text = card.get_text("\n")
            card_lines = [ln.strip() for ln in card_text.split("\n") if ln.strip()]
            # Число ціни і сам символ "₴" на реальних сайтах дуже часто
            # лежать у СУСІДНІХ, але ОКРЕМИХ тегах (наприклад
            # <span>170</span><span>₴</span>) — get_text("\n") тоді
            # розкладає їх на РІЗНІ "рядки", і пошук по кожному рядку
            # окремо (як було раніше) ніколи їх не з'єднає, хоча сама
            # регулярка (де \s вже матчить і перенос рядка) це б
            # спіймала. Тому ціну шукаємо по ВСЬОМУ тексту картки одним
            # блоком (через пробіл, не через рядки) — саме це і було
            # причиною "130 посилань знайдено, 0 товарів витягнуто" в
            # продакшн-логах.
            card_flat = card.get_text(" ")

            price = None
            m = _EPICENTR_PRICE_RE.search(card_flat)
            if m:
                price_str = m.group(1).replace(" ", "").replace("\xa0", "").replace(",", ".")
                try:
                    candidate_price = float(price_str)
                except ValueError:
                    candidate_price = 0
                if candidate_price > 0:
                    price = candidate_price

            if debug_first_card is None:
                debug_first_card = {
                    "href": href,
                    "link_text": link.get_text(" ", strip=True)[:80],
                    "price_found": price,
                    "card_flat_sample": card_flat[:400],
                }

            if price is None:
                continue

            # Назва — текст самого посилання (зазвичай і є назвою товару
            # або містить її в title/alt картинки); якщо посилання не
            # містить тексту (наприклад, це посилання-картинка) — беремо
            # title/alt, а як останній варіант — перший "схожий на назву"
            # рядок картки.
            name = link.get_text(" ", strip=True)
            if not name:
                name = (link.get("title") or "").strip()
            if not name:
                img = link.find("img")
                if img:
                    name = (img.get("alt") or img.get("title") or "").strip()
            if not name:
                for ln in card_lines:
                    if _EPICENTR_PRICE_RE.search(ln) or _RATING_LINE_RE.match(ln):
                        continue
                    if ln.lower() in _EPICENTR_NOISE_LINES:
                        continue
                    if len(ln) < 8 or len(ln) > 160:
                        continue
                    if not re.search(r"[a-zA-Zа-яА-ЯіІїЇєЄґҐ]", ln):
                        continue
                    name = ln
                    break
            if not name or len(name) < 4:
                continue

            seen_urls.add(product_url)
            results.append({"name": name, "price": price, "url": product_url})
            if len(results) >= limit:
                break

        if product_links and not results:
            # Посилання на товари є, а жодна картка не дала ні ціни, ні
            # назви — найімовірніше, розмітку сторінки знову змінили і
            # наші регулярки (_EPICENTR_PRICE_RE / card-root) більше не
            # потрапляють у потрібні теги. Це вже сигнал щодо ПАРСИНГУ,
            # а не мережі/блокування (бо посилання самі знайшлися).
            # Додатково лишаємо сирий приклад першої картки — щоб одразу
            # побачити, чого саме бракує (ціни чи назви), не ганяючи
            # деплой по колу ще раз.
            logger.warning(
                "live-price: found %d product links on %s but extracted 0 items "
                "(price/name parsing likely out of date). First card debug: %r",
                len(product_links), url, debug_first_card,
            )
    except Exception:
        logger.exception("live-price: unexpected parsing error for %s", url)
        results = []

    _EXTERNAL_PRICE_CACHE[url] = (time.time(), results)
    return results


# Прийменники/сполучники — не несуть сенсу для пошуку категорії, тому не
# враховуються як "слова" при розбитті запиту/ключових фраз на токени.
_SEARCH_STOPWORDS = {
    "для", "в", "на", "і", "й", "та", "по", "з", "із", "до", "під", "над",
    "о", "об", "у", "без", "про", "як", "что", "как", "это", "или", "або",
}
_WORD_RE = re.compile(r"[a-zа-яіїєґ0-9]+")


def _tokenize_query(text: str) -> list[str]:
    words = _WORD_RE.findall(text.lower())
    return [w for w in words if len(w) >= 3 and w not in _SEARCH_STOPWORDS]


def _words_match(a: str, b: str) -> bool:
    """
    Порівняння двох слів із допуском на відмінки/форми слова: точний збіг,
    або одне є префіксом іншого (ловить більшість відмінкових закінчень —
    "цемент"/"цементу", "саморіз"/"саморізи" — хоча не всі, бо в укр./рос.
    мовах закінчення іноді змінює й кінець кореня, а не лише додає літери;
    для короткого кореня (<=3 літер, напр. "осб", "пва") вимагаємо точного
    збігу, щоб не ловити випадкові збіги).
    """
    if a == b:
        return True
    shorter, longer = (a, b) if len(a) <= len(b) else (b, a)
    if len(shorter) <= 3:
        return False
    return longer.startswith(shorter)


def find_live_source(query: str):
    """
    Було: порівняння ЦІЛОЮ ФРАЗОЮ (підрядок в один чи інший бік) — тому
    двослівний запит на кшталт "клей пва" не знаходив НІЧОГО, бо жодна з
    curated-фраз не збігалася і не містила його цілком. Тепер порівнюємо
    ПО ОКРЕМИХ СЛОВАХ: рахуємо, скільки слів запиту знайшли відповідник
    серед слів ключових фраз категорії, і обираємо категорію з НАЙБІЛЬШИМ
    числом збігів (а не першу-ліпшу) — так "клей пва" попаде саме в
    категорію "Клей ПВА" (2 збіги: клей + пва), а не в загальний
    "Клей для плитки" (1 збіг: лише клей).
    """
    q_words = _tokenize_query(query)
    if not q_words:
        return None

    best_entry = None
    best_score = 0
    for entry in EXTERNAL_LIVE_SOURCES:
        entry_words = entry.get("_kw_words")
        if entry_words is None:
            entry_words = set()
            for kw in entry["keywords"]:
                entry_words.update(_tokenize_query(kw))
            entry["_kw_words"] = entry_words
        score = sum(1 for qw in q_words if any(_words_match(qw, ew) for ew in entry_words))
        if score > best_score:
            best_score = score
            best_entry = entry
    return best_entry


